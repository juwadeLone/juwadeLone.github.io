#!/usr/bin/env python3
"""Build assets/injection-data.js from commit-pinned board-level CRAM injection campaigns.

Usage: python3 scripts/build_injection_data.py [--repos DIR]
DIR holds checkouts of xidian-csft, xidian-csft-platform and this site.
"""
import argparse, hashlib, json, math, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
Z = 1.96  # same constant as the campaign summarizers

CSA_BUILDS = [
    ("W17", "无保护基准", "Unprotected baseline"),
    ("TMR17", "整体三模冗余", "Whole-application TMR"),
    ("GR17", "分组降精度冗余", "Grouped reduced-precision redundancy"),
    ("GR17M2", "降精度冗余 · 副本窄 2 位", "RPR, replicas 2 bits narrower"),
    ("GR17M1A", "降精度冗余 · 副本窄 1 位", "RPR, replicas 1 bit narrower"),
    ("GR17P1", "降精度冗余 · 副本宽 1 位", "RPR, replicas 1 bit wider"),
    ("GR17P2", "降精度冗余 · 副本宽 2 位", "RPR, replicas 2 bits wider"),
]
BP_BUILDS = [
    ("V7", "无保护基准", "Unprotected baseline", 6888526),
    ("T7", "整体三模冗余", "Whole-application TMR", 21308037),
    ("P7C", "运行时检查 + 自动重跑", "Runtime check + automatic rerun", 14070316),
]


def wilson(k, n):
    p = k / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return [c - h, c + h]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def head(repo):
    return subprocess.check_output(["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip()


def utilization(report):
    for line in report.read_text().splitlines():
        if line.startswith("| k7_udp_ddr_top "):
            cells = [c.strip() for c in line.strip("|").split("|")]
            lut, ff, r36, r18, dsp = int(cells[2]), int(cells[6]), int(cells[7]), int(cells[8]), int(cells[9])
            return {"lut": lut, "ff": ff, "bram36": r36 + r18 / 2, "dsp": dsp}
    raise SystemExit(f"no top row in {report}")


def build_row(bid, zh, en, n, identical, changed, below, due, pool):
    fail = below + due
    ci = wilson(fail, n)
    return {"id": bid, "zh": zh, "en": en, "n": n, "identical": identical, "changed": changed,
            "below": below, "due": due, "fail": fail, "pool": pool, "share": fail / n, "shareCi": ci,
            "vuln": round(fail / n * pool), "vulnCi": [round(ci[0] * pool), round(ci[1] * pool)]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repos", type=Path, default=ROOT.parent)
    args = ap.parse_args()
    csft, plat = args.repos / "xidian-csft", args.repos / "xidian-csft-platform"
    csft_commit, plat_commit = head(csft), head(plat)
    sources, csa = [], []
    for bid, zh, en in CSA_BUILDS:
        summary = csft / "campaigns" / bid / "summary" / "summary.json"
        report = plat / "builds" / bid / "build" / "reports" / "util_impl.rpt"
        s = json.loads(summary.read_text())
        b = s["batches"]["e0_point"]
        row = build_row(bid, zh, en, b["valid"], b["identical"], b["changed"], b["below_line"], b.get("DUE", 0), s["pool"])
        assert abs(s["rates"]["below_line"]["share_ci"][0] - wilson(b["below_line"], b["valid"])[0]) < 1e-12
        row["util"] = utilization(report)
        csa.append(row)
        rel = summary.relative_to(csft).as_posix()
        sources.append({"path": "xidian-csft/" + rel, "commit": csft_commit, "sha256": sha(summary),
                        "url": f"https://github.com/juwadeLone/xidian-csft/tree/{csft_commit}/campaigns/{bid}"})
        sources.append({"path": "xidian-csft-platform/" + report.relative_to(plat).as_posix(), "commit": plat_commit, "sha256": sha(report)})
    bp_sheet = ROOT / "datasheets" / "bp.json"
    bp_json = json.loads(bp_sheet.read_text())
    bp = []
    for bid, zh, en, pool in BP_BUILDS:
        e0 = bp_json["builds"][bid]["e0"]
        row = build_row(bid, zh, en, e0["valid"], e0["identical"], e0["changed"], e0["below_line"], e0.get("DUE", 0), pool)
        assert abs(row["vuln"] - bp_json["builds"][bid]["failure"]["xsec"]) < 1, bid
        bp.append(row)
    sources.append({"path": "datasheets/bp.json", "sha256": sha(bp_sheet)})
    data = {
        "criterion": {"psnr_db": 50, "failure": "below_line + DUE"},
        "chains": [
            {"id": "csa", "code": "CSA 2048 × 2048", "device": "Kintex-7 XC7K325T", "repo": f"https://github.com/juwadeLone/xidian-csft/tree/{csft_commit}", "builds": csa},
            {"id": "bp", "code": "BP 2048 × 2048", "device": "Kintex-7 XC7K325T", "datasheet": "datasheets/bp.html", "builds": bp},
        ],
        "sources": sources,
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    out = ROOT / "assets" / "injection-data.js"
    out.write_text('"use strict";\n// Generated by scripts/build_injection_data.py from commit-pinned campaign summaries. Do not edit by hand.\nconst injectionData = ' + body + ";\n", encoding="utf-8")
    for chain in data["chains"]:
        for r in chain["builds"]:
            print(chain["id"], r["id"], f'{r["fail"]}/{r["n"]}', f'{r["share"]*100:.2f}%', r["pool"], r["vuln"], r["vulnCi"], r.get("util"))


if __name__ == "__main__":
    main()
