#!/usr/bin/env python3
"""Regenerate/check public catalog metadata from exact, read-only Git revisions."""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPOS = ROOT.parent
PINS = {
    "a7": ("256x256A7csimaga", "256x256A7csimaga", "1a23992fe7911a47abf826cf2608898a559bdc3c"),
    "k7": ("2048-2048cs-k7-sem", "2048-2048cs-k7-sem", "b9c7ece95b6882c0872890720a81a64072540c25"),
    "v7": ("csa4096x4096", "csa4096x4096", "d6bb2134af5253f488a338d6ae0423c4e99cbf89"),
    "bp": ("BP-FT-platform", "BP_FT_platform", "32ef587a1f01ea0fe4c151bfe9c14775e78eb82c"),
    "fft": ("fault-tolerant-SDF-FFT-designs", "fault_tolerant_SDF_FFT_designs", "f805c32ebcd03edb26b9ad95d074f2d285985287"),
    "cordic": ("cordic-seu", "cordic_seu", "c72a856c9c104a5205a3860a591ff9ca3278a897"),
    "simulation": ("seu-platform", "seu_platform", "9a906e7f28b8ca6f1dbff3116a60b27ff25c1eb4"),
}
FILES = {
    "a7-readme": ("a7", "README.md"),
    "a7-mig": ("a7", "ddr_prj.srcs/sources_1/ip/mig_7series_0/mig_a.prj"),
    "k7-readme": ("k7", "README.md"),
    "k7-mig": ("k7", "vivado/ip/k7_mig/k7_mig_axi256.prj"),
    "k7-historical-run": ("k7", "results/k7_port/gf3_board_run.json"),
    "v7-readme": ("v7", "README.md"),
    "v7-ddr": ("v7", "bd/design_ddr/hw_handoff/design_ddr_bd.tcl"),
    "v7-pcie": ("v7", "bd/design_xdma/hw_handoff/design_xdma_bd.tcl"),
    "bp-readme": ("bp", "README.md"),
    "bp-v4-run": ("bp", "experiments/bp_k7/results/board_run_V4.json"),
    "fft-readme": ("fft", "README.md"),
    "cordic-rtl": ("cordic", "rtl/dut/cordic_sin_pipe.sv"),
    "simulation-readme": ("simulation", "README.md"),
    "simulation-orbit": ("simulation", "docs/media/orbit.webp"),
    "simulation-effects": ("simulation", "docs/media/effects.png"),
}


def build():
    sources, raw = {}, {}
    for key, (repo_key, path) in FILES.items():
        local, repo, commit = PINS[repo_key]
        data = subprocess.check_output(["git", "-C", str(REPOS / local), "show", f"{commit}:{path}"])
        raw[key] = data
        sources[key] = {"repo": f"juwadeLone/{repo}", "commit": commit, "path": path,
                        "sha256": hashlib.sha256(data).hexdigest(),
                        "url": f"https://github.com/juwadeLone/{repo}/blob/{commit}/{path}"}
    memory = {}
    for board, key in (("a7", "a7-mig"), ("k7", "k7-mig"), ("v7", "v7-ddr")):
        text = raw[key].decode()
        field = lambda name: [int(v) for v in re.findall(fr"<{name}>(\d+)</{name}>", text)]
        widths, rows, cols, banks = (field(n) for n in ("DataWidth", "RowAddress", "ColAddress", "BankAddress"))
        capacities = [(1 << (r + c + b)) * w // 8 for w, r, c, b in zip(widths, rows, cols, banks)]
        assert len(capacities) == (2 if board == "v7" else 1)
        memory[board] = {"source_id": key, "data_width_bits": widths, "row_bits": rows,
                         "column_bits": cols, "bank_bits": banks, "channel_bytes": capacities,
                         "total_bytes": sum(capacities), "basis": "MIG configuration geometry; not physical capacity acceptance testing"}
    bp = json.loads(raw["bp-v4-run"])
    return {"scope": "Configured hardware, algorithms, primitives and validation cases are separate. No flight qualification is asserted.",
            "source_access": "Source repository access may be required. No proprietary RTL or raw GF-3 data/images are redistributed.",
            "sources": sources, "memory": memory,
            "bp_v4": {"source_id": "bp-v4-run", "runs": [{k: row[k] for k in ("run", "ok", "run_s", "read_s", "pixels_differing")} for row in bp["runs"]]},
            "k7_historical_run": {"source_id": "k7-historical-run", "pass_gate": json.loads(raw["k7-historical-run"])["pass_gate"], "used_as_benchmark": False}}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "assets/catalog-provenance.json"
    data = build()
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    browser_target = ROOT / "assets/catalog-sources.js"
    browser_payload = "// Generated by scripts/catalog_sources.py; do not edit.\nconst catalogSources = " + json.dumps(data["sources"], ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        assert target.read_text() == payload, "Catalog provenance differs from pinned source bytes"
        assert browser_target.read_text() == browser_payload, "Browser source index differs"
        print("Catalog source hashes, memory geometry and run summaries verified.")
    else:
        target.write_text(payload)
        browser_target.write_text(browser_payload)
